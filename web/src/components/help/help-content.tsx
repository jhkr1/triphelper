import type { ReactNode } from "react";

/*
 * 사용법 도움말 내용 ("이럴 땐 이렇게").
 * 버튼 이름은 실제 화면 글자와 똑같이 적는다 (화면 문구를 바꾸면 여기도 함께 고친다).
 */

export type HelpPage = "trip" | "board" | "dest" | "home";
export interface HelpItem { q: string; a: ReactNode }
export interface HelpSection { label: string; groups: { name: string; items: HelpItem[] }[] }

/** 화면의 버튼 이름 */
const B = ({ children }: { children: ReactNode }) => <span className="help__kbd">{children}</span>;
const Tip = ({ children }: { children: ReactNode }) => <p className="help__tip">{children}</p>;

/** 주소 → 도움말 페이지 */
export function helpPageOf(pathname: string): HelpPage {
  if (pathname.startsWith("/trip")) return "trip";
  if (pathname.startsWith("/board")) return "board";
  if (pathname.startsWith("/destinations")) return "dest";
  return "home";
}

